"""server.conf, generated here from validated parameters only.

The panel is not trusted to write this file: a directive such as "up" or "script-security" would
give root to whoever controls it. Fixed values come from the root-owned config; the rest are
typed, already-validated values formatted from parsed objects, so nothing free-form is interpolated.
"""
import ipaddress
import os

from ..config import CONFIG
from .common import atomic_write


def render(s: dict) -> str:
    proto = CONFIG.proto
    if proto not in ("udp", "tcp"):
        raise ValueError("invalid protocol in the configuration")
    net = ipaddress.IPv4Network(CONFIG.subnet)
    lines = [
        "# Generated by ovpn-panel: manual changes will be overwritten",
        f"port {int(CONFIG.port)}",
        f"proto {proto}",
        "dev tun",
        "ca ca.crt",
        "cert server.crt",
        "key server.key",
        "dh none",
        "tls-crypt tc.key",
        "tls-version-min 1.2",
        "crl-verify crl.pem",
        "client-config-dir ccd",
        "topology subnet",
        f"server {net.network_address} {net.netmask}",
        "keepalive 10 120",
        "data-ciphers AES-256-GCM:AES-128-GCM:CHACHA20-POLY1305",
        "user nobody",
        "group nogroup",
        "persist-key",
        "persist-tun",
        f"management {CONFIG.mgmt_socket} unix",
        "verb 3",
    ]
    if proto == "udp":
        lines.append("explicit-exit-notify 1")
    if s["full_tunnel"]:
        lines.append('push "redirect-gateway def1 bypass-dhcp"')
        # keeps Windows clients from resolving names outside the tunnel
        lines.append('push "block-outside-dns"')
    else:
        for r in s["routes"]:
            n = ipaddress.IPv4Network(r)
            lines.append(f'push "route {n.network_address} {n.netmask}"')
        # In split tunnel the DNS servers are outside the routed networks: without a host route
        # the client sends its queries out of the normal connection and names stop resolving,
        # even though the networks themselves are reachable.
        for d in s["dns"]:
            lines.append(f'push "route {ipaddress.IPv4Address(d)} 255.255.255.255"')
    lines += [f'push "dhcp-option DNS {ipaddress.IPv4Address(d)}"' for d in s["dns"]]
    if s["client_to_client"]:
        lines.append("client-to-client")
    return "\n".join(lines) + "\n"


def read() -> str:
    path = os.path.join(CONFIG.server_dir, "server.conf")
    try:
        with open(path) as f:
            return f.read()
    except FileNotFoundError:
        return ""


def write_text(text: str):
    atomic_write(os.path.join(CONFIG.server_dir, "server.conf"), text, 0o640)


def write(s: dict):
    write_text(render(s))
